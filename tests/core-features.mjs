    const post = async (extra = {}) => api('/api/transactions', { cookie, body: { ...base, requestKey: randomUUID(), ...extra }, status: 201 });
    const original = await post();
    await api('/api/transactions', { cookie, body: { ...base, expectedUserId: otherUser.id, requestKey: randomUUID() }, status: 409 });
    const cancellation = { id: original.json.id, action: 'cancel', requestKey: randomUUID(), reason: 'Nhập nhầm' };
    await api('/api/transactions/reverse', { cookie: other, body: cancellation, status: 404 });
    const reversed = await api('/api/transactions/reverse', { cookie, body: cancellation, status: 201 });
    const retry = await api('/api/transactions/reverse', { cookie, body: cancellation, status: 201 });
    check(reversed.json.id === retry.json.id, 'Cancellation is idempotent');
    await api('/api/transactions/reverse', { cookie, body: { ...cancellation, requestKey: randomUUID() }, status: 409 });
    await api('/api/transactions/reverse', { cookie, body: { ...cancellation, id: reversed.json.id }, status: 400 });
    check((await api(reportUrl, { cookie })).json.expense === 0, 'Cancellation removes expense from totals without deleting history');
    const source = await post({ amount: '100.05' });
    const correction = { id: source.json.id, action: 'correct', requestKey: randomUUID(), reason: 'Sửa số tiền', replacement: { ...base, amount: '70.03', requestKey: randomUUID() } };
    const corrected = await api('/api/transactions/reverse', { cookie, body: correction, status: 201 });
    const correctedRetry = await api('/api/transactions/reverse', { cookie, body: correction, status: 201 });
    check(corrected.json.replacementId === correctedRetry.json.replacementId, 'Correction retry returns the same replacement');
    await api('/api/transactions/reverse', { cookie, body: { ...correction, replacement: { ...correction.replacement, amount: '90.00' } }, status: 409 });
    const report = (await api(reportUrl, { cookie })).json;
    check(report.expense === 70.03 && Number(report.breakdown[0].amount) === 70.03, 'Reports and category breakdown subtract reversal amounts');
    check(report.transactions.length === 5 && report.transactions.find((t) => t.id === source.json.id).reversed && report.transactions.find((t) => t.id === corrected.json.id).reason === correction.reason, 'History retains original, reversal, replacement and reason');
    const rollbackSource = await post({ amount: '1' });
    await api('/api/transactions/reverse', { cookie, body: { ...correction, id: rollbackSource.json.id, requestKey: randomUUID(), replacement: { ...base, amount: '0', requestKey: randomUUID() } }, status: 400 });
    const [rollback] = await admin.execute('SELECT id FROM transactions WHERE user_id = ? AND reverses_id = ?', [user.id, rollbackSource.json.id]);
    check(rollback.length === 0, 'Invalid correction rolls back the reversal as well');
    const transfer = await post({ kind: 'transfer', targetId, amount: '12.34' });
    await api('/api/transactions/reverse', { cookie, body: { ...cancellation, id: transfer.json.id, requestKey: randomUUID() }, status: 201 });
    const transferReport = (await api(reportUrl, { cookie })).json;
    check(transferReport.transactions.filter((t) => t.kind === 'transfer').length === 2, 'Both transfer and its reversal appear once');
    const racedKey = randomUUID();
    const raced = await Promise.all(Array.from({ length: 4 }, () => post({ requestKey: racedKey, amount: '2.01' })));
    check(new Set(raced.map((r) => r.json.id)).size === 1, 'Concurrent duplicate submissions create one transaction');
    const racedCancel = { ...cancellation, id: raced[0].json.id, requestKey: randomUUID() };
    const raceReversals = await Promise.all(Array.from({ length: 3 }, () => api('/api/transactions/reverse', { cookie, body: racedCancel, status: 201 })));
    check(new Set(raceReversals.map((r) => r.json.id)).size === 1, 'Concurrent reversals remain unique');
    const [balanced] = await admin.execute('SELECT transaction_id, SUM(amount) AS amount, COUNT(*) AS count FROM transaction_entries WHERE user_id = ? GROUP BY transaction_id', [user.id]);
    check(balanced.every((r) => r.amount === '0.00' && r.count === 2), 'Every new ledger transaction has exactly two balanced entries');

    await api('/api/wallets', { cookie: other, body: { id: walletId, name: 'Hacked' }, status: 404 });
    await api('/api/categories', { cookie: other, body: { id: categoryId, archived: true }, status: 404 });
    await api('/api/wallets', { cookie, body: { id: walletId, archived: true }, status: 409 });
    await api('/api/wallets', { cookie, body: { id: targetId, name: 'Ví đổi tên' } });
    await api('/api/wallets', { cookie, body: { id: targetId, archived: true } });
    check(!(await api('/api/wallets', { cookie })).json.wallets.some((w) => w.id === targetId), 'Archived wallets are excluded from new entries');
    check((await api('/api/wallets?all=1', { cookie })).json.wallets.some((w) => w.id === targetId && w.archived), 'Wallet archive preserves records');
    await api('/api/transactions', { cookie, body: { ...base, kind: 'transfer', targetId, requestKey: randomUUID() }, status: 404 });
    await api('/api/wallets', { cookie, body: { id: targetId, archived: false } });
