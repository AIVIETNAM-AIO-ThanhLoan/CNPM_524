    await api('/api/auth/register', { body: account, status: 201 });
    await api('/api/auth/register', { body: { ...account, account: 'core-b@example.com' }, status: 201 });
    const { cookie } = await api('/api/auth/login', { body: account });
    const { cookie: other } = await api('/api/auth/login', { body: { ...account, account: 'core-b@example.com' } });
    const user = (await api('/api/auth/me', { cookie })).json.user;
    const otherUser = (await api('/api/auth/me', { cookie: other })).json.user;
    const wallets = (await api('/api/wallets', { cookie })).json.wallets;
    const categories = (await api('/api/categories', { cookie })).json.categories;
    const walletId = wallets[0].id, targetId = wallets[1].id;
    const categoryId = categories.find((c) => c.kind === 'expense').id;
    const incomeCategoryId = categories.find((c) => c.kind === 'income').id;
    const reportUrl = '/api/finance?start=2026-03-01&end=2026-03-31';
